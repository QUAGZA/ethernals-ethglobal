// Copies the compiled HireLedger ABI + bytecode into packages/shared so the server and web app
// can use them without Hardhat. Run via `pnpm contracts:build`.
const fs = require("node:fs");
const path = require("node:path");

const artifact = require(path.join(__dirname, "..", "artifacts", "contracts", "HireLedger.sol", "HireLedger.json"));
const out = path.join(__dirname, "..", "..", "shared", "src", "hire-ledger-abi.ts");

const content = `// GENERATED by packages/contracts/scripts/export-abi.cjs — do not edit by hand.
// Re-generate with: pnpm contracts:build
export const hireLedgerAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const hireLedgerBytecode = "${artifact.bytecode}" as \`0x\${string}\`;
`;

fs.writeFileSync(out, content);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${artifact.abi.length} ABI entries, ${(artifact.bytecode.length - 2) / 2} bytes)`);
