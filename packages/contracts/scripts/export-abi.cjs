// Copies compiled ABIs into packages/shared so the server, verifier and web app can use them without Hardhat.
// Run via `pnpm contracts:build`.
//  - HireLedger (ABI + bytecode)        -> packages/shared/src/hire-ledger-abi.ts
//  - ITaskEscrow (frozen interface ABI) -> packages/shared/src/task-escrow-abi.ts
const fs = require("node:fs");
const path = require("node:path");

const artifacts = path.join(__dirname, "..", "artifacts", "contracts");
const shared = path.join(__dirname, "..", "..", "shared", "src");

function write(file, body) {
  const out = path.join(shared, file);
  fs.writeFileSync(out, `// GENERATED by packages/contracts/scripts/export-abi.cjs — do not edit by hand.\n// Re-generate with: pnpm contracts:build\n${body}`);
  console.log(`Wrote ${path.relative(process.cwd(), out)}`);
}

const ledger = require(path.join(artifacts, "HireLedger.sol", "HireLedger.json"));
write(
  "hire-ledger-abi.ts",
  `export const hireLedgerAbi = ${JSON.stringify(ledger.abi, null, 2)} as const;\n\nexport const hireLedgerBytecode = "${ledger.bytecode}" as \`0x\${string}\`;\n`,
);

const escrowInterface = require(path.join(artifacts, "ITaskEscrow.sol", "ITaskEscrow.json"));
write(
  "task-escrow-abi.ts",
  `// ABI of the FROZEN ITaskEscrow interface. TaskEscrow implements it exactly.\nexport const taskEscrowAbi = ${JSON.stringify(escrowInterface.abi, null, 2)} as const;\n`,
);
